CREATE TABLE audit_event (
    entity_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    "timestamp" TIMESTAMP(6) NOT NULL,
    action VARCHAR(255) NOT NULL,
    entity_type VARCHAR(255) NOT NULL,
    username VARCHAR(255) NOT NULL,
    CONSTRAINT audit_event_action_check
        CHECK (action IN (
            'CONTRACT_CREATED',
            'CONTRACT_UPDATED',
            'CONTRACT_DELETED',
            'CONTRACT_RENEWED',
            'REVIEW_STARTED',
            'REVIEW_APPROVED',
            'REVIEW_REJECTED',
            'STATUS_CHANGED'
        ))
);

CREATE TABLE contracts (
    auto_renewal BOOLEAN,
    contract_value NUMERIC(38,2),
    end_date DATE NOT NULL,
    start_date DATE NOT NULL,
    unlimited_liability BOOLEAN,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    contract_number VARCHAR(255) NOT NULL UNIQUE,
    contract_status VARCHAR(255) NOT NULL,
    contract_type VARCHAR(255) NOT NULL,
    counterparty VARCHAR(255) NOT NULL,
    governing_law VARCHAR(255),
    legal_review_reason VARCHAR(255),
    legal_review_type VARCHAR(255) NOT NULL,
    review_status VARCHAR(255) NOT NULL,
    risk_level VARCHAR(255) NOT NULL,
    title VARCHAR(255) NOT NULL,

    CONSTRAINT contracts_contract_status_check
        CHECK (contract_status IN (
            'DRAFT',
            'ACTIVE',
            'SIGNED',
            'EXPIRED',
            'TERMINATED',
            'ARCHIVED'
        )),

    CONSTRAINT contracts_contract_type_check
        CHECK (contract_type IN (
            'NDA',
            'SERVICE',
            'PURCHASE',
            'SALES',
            'EMPLOYMENT',
            'LICENSE',
            'SUPPLIER',
            'FRAMEWORK'
        )),

    CONSTRAINT contracts_legal_review_type_check
        CHECK (legal_review_type IN (
            'STANDARD',
            'ENHANCED'
        )),

    CONSTRAINT contracts_review_status_check
        CHECK (review_status IN (
            'NOT_REQUIRED',
            'PENDING',
            'IN_REVIEW',
            'APPROVED',
            'REJECTED'
        )),

    CONSTRAINT contracts_risk_level_check
        CHECK (risk_level IN (
            'LOW',
            'MEDIUM',
            'HIGH'
        ))
);

CREATE TABLE contract_approvals (
    contract_id BIGINT NOT NULL,
    decided_at TIMESTAMP(6),
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    approval_role VARCHAR(255) NOT NULL,
    decided_by VARCHAR(255),
    status VARCHAR(255) NOT NULL,

    CONSTRAINT contract_approvals_approval_role_check
        CHECK (approval_role IN (
            'LEGAL',
            'FINANCE',
            'MANAGEMENT',
            'COMPLIANCE'
        )),

    CONSTRAINT contract_approvals_status_check
        CHECK (status IN (
            'PENDING',
            'APPROVED',
            'REJECTED'
        )),

    CONSTRAINT fk_contract_approvals_contract
        FOREIGN KEY (contract_id)
        REFERENCES contracts(id)
);

CREATE TABLE contract_renewal_history (
    new_end_date DATE NOT NULL,
    previous_end_date DATE NOT NULL,
    contract_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    renewed_at TIMESTAMP(6) NOT NULL,
    renewed_by VARCHAR(255) NOT NULL,

    CONSTRAINT fk_contract_renewal_history_contract
        FOREIGN KEY (contract_id)
        REFERENCES contracts(id)
);

CREATE TABLE legal_review_decision_history (
    contract_id BIGINT NOT NULL,
    decided_at TIMESTAMP(6) NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    decided_by VARCHAR(255) NOT NULL,
    reason VARCHAR(255) NOT NULL,
    review_type VARCHAR(255) NOT NULL,

    CONSTRAINT legal_review_decision_history_review_type_check
        CHECK (review_type IN (
            'STANDARD',
            'ENHANCED'
        )),

    CONSTRAINT fk_legal_review_decision_history_contract
        FOREIGN KEY (contract_id)
        REFERENCES contracts(id)
);

CREATE TABLE risk_assessment (
    assessed_at TIMESTAMP(6) NOT NULL,
    contract_id BIGINT NOT NULL,
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    assessed_by VARCHAR(255) NOT NULL,
    risk_level VARCHAR(255) NOT NULL,

    CONSTRAINT risk_assessment_risk_level_check
        CHECK (risk_level IN (
            'LOW',
            'MEDIUM',
            'HIGH'
        )),

    CONSTRAINT fk_risk_assessment_contract
        FOREIGN KEY (contract_id)
        REFERENCES contracts(id)
);
